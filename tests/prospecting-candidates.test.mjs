  const before=await listLeadPage(user,new URLSearchParams("fit=todos"));
  const untouchedLead=before.rows.find((lead)=>lead.cnpj===untouched.cnpj);
  const requestedLead=before.rows.find((lead)=>lead.cnpj===requested.cnpj);
  const potentialLead=before.rows.find((lead)=>lead.cnpj===potential.cnpj);
  const overdueLead=before.rows.find((lead)=>lead.cnpj===overdue.cnpj);
  assert.equal(untouchedLead.lead_score,100);
  await recordProspectingActivity(user,requestedLead.id,{channel:"WhatsApp",result:"Solicitou material",notes:"Pediu portfólio.",next_action:"Enviar portfólio",next_date:"2099-01-01"});
