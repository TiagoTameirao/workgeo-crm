import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
process.env.DATABASE_URL = "";
process.env.NODE_ENV = "test";
const dir = mkdtempSync(path.join(tmpdir(), "wg-admin-catalog-"));
process.env.CRM_SQLITE_PATH = path.join(dir, "test.sqlite");
const { migrate, query, get, list, close } = await import("../lib/db.mjs");
const { seedDatabase } = await import("../lib/seed.mjs");
const { changeAdministrativeCatalog, saveRecord, stateFor } = await import("../lib/domain.mjs");
const { administrativeCatalog } = await import("../lib/administrative-catalog.mjs");
const user = { id: "catalog-admin", name: "Josi", role: "Administrativo" };
before(async () => {
  await migrate(); await seedDatabase();
  await query("INSERT INTO users(id,name,email,password_hash,role) VALUES($1,$2,$3,$4,$5)", [user.id, user.name, "catalog@example.invalid", "not-used", user.role]);
});
after(async () => { await close(); rmSync(dir, { recursive: true, force: true }); });
const document = (name) => ({ name, unit_id: "unit-001", owner: "Josi", revision: 1, due_date: "2026-11-30" });
test("prospectos não entram automaticamente no administrativo; inclusão e retirada preservam o cadastro e os documentos", async () => {
  assert.equal((await list("units")).length, 27);
  assert.deepEqual((await administrativeCatalog()).client_ids, []);
  await assert.rejects(saveRecord(user, "admin_documents", document("Não elegível")), /Catálogos/);
  await changeAdministrativeCatalog(user, { action: "add-client", unit_id: "unit-001" });
  const record = await saveRecord(user, "admin_documents", document("Histórico preservado"));
  await changeAdministrativeCatalog(user, { action: "remove-client", unit_id: "unit-001" });
  assert.equal((await get("admin_documents", record.id)).name, "Histórico preservado");
  assert.ok(await get("units", "unit-001"));
  await saveRecord(user, "admin_documents", { notes: "Continuidade do documento antigo" }, record.id, record.version);
  await assert.rejects(saveRecord(user, "admin_documents", document("Nova exigência bloqueada")), /Catálogos/);
  await assert.rejects(changeAdministrativeCatalog({ ...user, role: "Comercial" }, { action: "add-client", unit_id: "unit-002" }), /perfil/);
  assert.equal((await stateFor({ ...user, role: "Comercial" })).administrativeCatalog, null);
});
test("administrativo cadastra empresa atendida e contato diretamente, sem gerar oportunidade e sem duplicar unidade", async () => {
  const before = (await list("companies")).length;
  await assert.rejects(changeAdministrativeCatalog(user, { action: "create-client", company_name: "Inválido QA", email: "inválido" }), /e-mail/);
  assert.equal((await list("companies")).length, before);
  const result = await changeAdministrativeCatalog(user, { action: "create-client", company_name: "Cliente atendido QA", city: "BH", phone: "(31) 99999-9999", email: "cliente@example.invalid" });
  assert.ok(result.client_ids.includes(result.created_unit_id));
  const unit = await get("units", result.created_unit_id);
  assert.equal(unit.source, "Cadastro administrativo — cliente atendido");
  assert.ok((await list("contacts")).some((contact) => contact.unit_id === unit.id && contact.phone === "31999999999"));
  assert.equal((await list("opportunities")).length, 0);
  await assert.rejects(changeAdministrativeCatalog(user, { action: "create-client", company_name: "Cliente atendido QA" }), /já está cadastrada/);
});
test("modalidades e serviços retirados saem de novas seleções sem invalidar histórico", async () => {
  await changeAdministrativeCatalog(user, { action: "add-client", unit_id: "unit-001" });
  let catalog = await changeAdministrativeCatalog(user, { action: "add-service-type", name: "Inventário" });
  await assert.rejects(changeAdministrativeCatalog(user, { action: "add-service-type", name: " inventario " }), /já existe/);
  let service = await saveRecord(user, "services", { name: "Campanha Inventário QA", modality: "Inventário", unit_id: "unit-001", external_reference: "Pedido QA", scope: "Estoque QA" });
  const invoice = await saveRecord(user, "invoices", { name: "Medição QA", service_id: service.id, unit_id: "unit-001", owner: "Josi", next_date: "2026-11-01", amount: "25.00" });
  await changeAdministrativeCatalog(user, { action: "set-service", id: service.id, active: false });
  await assert.rejects(saveRecord(user, "admin_documents", { ...document("Novo vínculo"), service_id: service.id }), /retirado/);
  await saveRecord(user, "invoices", { notes: "Atualização permitida" }, invoice.id, invoice.version);
  const type = catalog.service_types.find((item) => item.name === "Inventário");
  await changeAdministrativeCatalog(user, { action: "set-service-type", id: type.id, active: false });
  service = await get("services", service.id);
  await saveRecord(user, "services", { notes: "Histórico ativo" }, service.id, service.version);
  await assert.rejects(saveRecord(user, "services", { name: "Novo Inventário", modality: "Inventário", unit_id: "unit-001", external_reference: "QA", scope: "QA" }), /Modalidade/);
  await changeAdministrativeCatalog(user, { action: "set-service-type", id: type.id, active: true });
  await changeAdministrativeCatalog(user, { action: "set-service", id: service.id, active: true });
  await saveRecord(user, "admin_documents", { ...document("Vínculo reativado"), service_id: service.id });
});
test("alterações paralelas no catálogo não perdem inclusões", async () => {
  await Promise.all(["unit-002", "unit-003"].map((unit_id) => changeAdministrativeCatalog(user, { action: "add-client", unit_id })));
  const catalog = await administrativeCatalog();
  assert.ok(catalog.client_ids.includes("unit-002"));
  assert.ok(catalog.client_ids.includes("unit-003"));
  assert.ok((await query("SELECT * FROM audit WHERE entity=$1 AND record_id=$2", ["settings", "administrative-catalog"])).length);
});
